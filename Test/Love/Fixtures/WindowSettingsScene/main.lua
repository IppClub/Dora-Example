local frames = 0

function love.load()
	local width, height, settings = love.window.getMode()
	assert(width == 320 and height == 180 and settings.resizable)
	assert(not settings.fullscreen and settings.display == 1 and not settings.highdpi)
	assert(love.window.updateMode({resizable = false}))
	width, height, settings = love.window.getMode()
	assert(width == 320 and height == 180 and not settings.resizable)
	assert(love.window.updateMode({resizable = true}))
	width, height, settings = love.window.getMode()
	assert(width == 320 and height == 180 and settings.resizable)
	assert(not love.window.updateMode({fullscreen = true}))
	width, height, settings = love.window.getMode()
	assert(width == 320 and height == 180 and settings.resizable)
	local desktopWidth, desktopHeight = love.window.getDesktopDimensions()
	assert(desktopWidth == 320 and desktopHeight == 180)
	assert(love.window.getDisplayCount() == 1)
	assert(love.window.getDisplayName(1) == "Dora LoveNode")
	assert(love.window.getDisplayOrientation() == "landscape")
	assert(#love.window.getFullscreenModes() == 0)
	local fullscreen, fullscreenType = love.window.getFullscreen()
	assert(not fullscreen and fullscreenType == "desktop")
	assert(love.window.setFullscreen(false) and not love.window.setFullscreen(true))
	assert(love.window.getIcon() == nil)
	local x, y, display = love.window.getPosition()
	assert(x == 0 and y == 0 and display == 1)
	x, y, desktopWidth, desktopHeight = love.window.getSafeArea()
	assert(x == 0 and y == 0 and desktopWidth == 320 and desktopHeight == 180)
	assert(love.window.getTitle() == "Dora virtual settings")
	love.window.setTitle("Runtime virtual title")
	assert(love.window.getTitle() == "Runtime virtual title")
	assert(love.window.getVSync() == -1)
	love.window.setVSync(false)
	assert(love.window.getVSync() == 0)
	love.window.setDisplaySleepEnabled(true)
	assert(love.window.isDisplaySleepEnabled())
	love.window.setDisplaySleepEnabled(false)
	assert(not love.window.isDisplaySleepEnabled())
	assert(love.window.isOpen() and love.window.isVisible())
	-- LoveNode assigns the initial input owner after love.load returns.
	assert(not love.window.hasFocus() and not love.window.hasMouseFocus())
	assert(not love.window.isMaximized() and not love.window.isMinimized())
	assert(not pcall(love.window.getDisplayName, 2))
end

function love.update()
	frames = frames + 1
	if frames == 2 then
		assert(love.window.hasFocus() and love.window.hasMouseFocus())
		assert(love.window.updateMode(512, 288, {resizable = false}))
		local width, height, settings = love.window.getMode()
		assert(width == 512 and height == 288 and not settings.resizable)
		local pixelWidth, pixelHeight = love.graphics.getPixelDimensions()
		assert(pixelWidth == width and pixelHeight == height and love.graphics.getDPIScale() == 1)
		assert(love.window.getDPIScale() == 1 and love.window.getNativeDPIScale() == 1)
		local px, py = love.window.toPixels(width, height)
		local logicalWidth, logicalHeight = love.window.fromPixels(px, py)
		assert(px == width and py == height and logicalWidth == width and logicalHeight == height)
		print("LOVE_WINDOW_UPDATE_MODE_PASS", width, height, settings.resizable)
	elseif frames == 30 then
		assert(love.event.quit())
	end
end

function love.draw()
	local width, height = love.graphics.getDimensions()
	love.graphics.clear(0.025, 0.04, 0.075, 1)
	love.graphics.setColor(0.2, 0.9, 0.65, 1)
	love.graphics.rectangle("line", 8, 8, width - 16, height - 16)
end
