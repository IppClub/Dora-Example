local helper = require("scene.helper")

function love.load()
	assert(virtual_window_booted)
	assert(helper.label == "SOURCE ROOT MODULE")
	local width, height, flags = love.window.getMode()
	assert(width == 480 and height == 270)
	assert(flags.fullscreen == false and flags.resizable == true)
	assert(love.window.getDPIScale() == 1 and love.window.getNativeDPIScale() == 1)
	assert(love.window.toPixels(24) == 24 and love.window.fromPixels(24) == 24)
	local px, py = love.window.toPixels(24, 12)
	local lx, ly = love.window.fromPixels(px, py)
	assert(px == 24 and py == 12 and lx == 24 and ly == 12)
end

function love.draw()
	local width, height = love.graphics.getDimensions()
	assert(width == 480 and height == 270)
	assert(love.graphics.getWidth() == width and love.graphics.getHeight() == height)
	local pixelWidth, pixelHeight = love.graphics.getPixelDimensions()
	assert(pixelWidth == width and pixelHeight == height)
	assert(love.graphics.getPixelWidth() == width and love.graphics.getPixelHeight() == height)
	assert(love.graphics.getDPIScale() == 1)
	love.graphics.clear(0.04, 0.12, 0.1, 1)
	love.graphics.setColor(0.15, 0.9, 0.55, 1)
	love.graphics.rectangle("fill", 0, 0, width, 28)
	love.graphics.rectangle("fill", 0, height - 28, width, 28)
	love.graphics.setColor(1, 0.8, 0.2, 1)
	love.graphics.rectangle("line", 24, 48, width - 48, height - 96)
	love.graphics.line(24, 48, width - 24, height - 48)
	love.graphics.line(width - 24, 48, 24, height - 48)
end
