			and mip2Width == entry.width / 2 and mip2Height == entry.height / 2
			and lastMipWidth == 1 and lastMipHeight == 1
			and compressed:getSize() == expectedSize,
			entry.container .. "/" .. entry.format .. ": " .. compressed:getFormat()
				.. " " .. parsedWidth .. "x" .. parsedHeight
				.. " mips=" .. compressed:getMipmapCount()
				.. " mip2=" .. mip2Width .. "x" .. mip2Height
				.. " last=" .. lastMipWidth .. "x" .. lastMipHeight
				.. " bytes=" .. compressed:getSize())
