local function u32(value)
	return string.pack("<I4", value)
end

local function u64(value)
	return string.pack("<I8", value)
end

local function makeDDS(fourcc, blockSize, blocks)
	local header = "DDS "
		.. u32(124) .. u32(0x000a1007)
		.. u32(4) .. u32(4) .. u32(blockSize) .. u32(0) .. u32(3)
		.. string.rep(u32(0), 11)
		.. u32(32) .. u32(4) .. fourcc
		.. u32(0) .. u32(0) .. u32(0) .. u32(0) .. u32(0)
		.. u32(0x00401008) .. u32(0) .. u32(0) .. u32(0) .. u32(0)
	return header .. table.concat(blocks)
end

local function dxtColorBlocks()
	-- A complete 4x4, 2x2, 1x1 mip chain. Every level occupies one block;
	-- color index 0 selects opaque red, green, then blue. DXT3 uses explicit
	-- opaque alpha nibbles and DXT5 selects its first (opaque) alpha endpoint.
	local red = string.char(0x00, 0xf8, 0xe0, 0x07, 0, 0, 0, 0)
	local green = string.char(0xe0, 0x07, 0x1f, 0x00, 0, 0, 0, 0)
	local blue = string.char(0x1f, 0x00, 0x00, 0x00, 0, 0, 0, 0)
	return {red, green, blue}
end

local function makeDXT(format)
	local colors = dxtColorBlocks()
	if format == "DXT1" then
		return makeDDS(format, 8, colors)
	elseif format == "DXT3" then
		local alpha = string.rep(string.char(0xff), 8)
		return makeDDS(format, 16, {alpha .. colors[1], alpha .. colors[2], alpha .. colors[3]})
	elseif format == "DXT5" then
		local alpha = string.char(0xff, 0x00) .. string.rep("\0", 6)
		return makeDDS(format, 16, {alpha .. colors[1], alpha .. colors[2], alpha .. colors[3]})
	end
	error("unsupported test DXT format " .. tostring(format))
end

local function makeKTX(internalFormat, blocks, baseFormat, width, height)
	width = width or 4
	height = height or 4
	local header = string.char(0xab, 0x4b, 0x54, 0x58, 0x20, 0x31,
		0x31, 0xbb, 0x0d, 0x0a, 0x1a, 0x0a)
		.. u32(0x04030201) .. u32(0) .. u32(1) .. u32(0)
		.. u32(internalFormat) .. u32(baseFormat or 0x1908)
		.. u32(width) .. u32(height) .. u32(0) .. u32(0)
		.. u32(1) .. u32(#blocks) .. u32(0)
	local levels = {}
	for index, block in ipairs(blocks) do
		levels[index] = u32(#block) .. block
	end
	return header .. table.concat(levels)
end

local function makeKTXDXT1()
	return makeKTX(0x83f1, dxtColorBlocks())
end

local function makeKTXASTC4x4()
	-- Generated deterministically from opaque red RGBA8 using the vendored
	-- astc-encoder at ASTCENC_PRE_MEDIUM. One block represents every mip.
	local red = string.char(0xfc, 0xfd, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
		0xff, 0xff, 0x00, 0x00, 0x00, 0x00, 0xff, 0xff)
	return makeKTX(0x93b0, {red, red, red})
end

local function astcRedBlocks(width, height)
	-- ASTC void-extent opaque red block. This encoding is footprint-independent,
	-- so the same deterministic block covers every Love 11.5 ASTC block size.
	local red = string.char(0xfc, 0xfd, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
		0xff, 0xff, 0x00, 0x00, 0x00, 0x00, 0xff, 0xff)
	local blocks = {}
	local extent = math.max(width, height)
	repeat
		blocks[#blocks + 1] = red
		extent = math.floor(extent / 2)
	until extent < 1
	return blocks
end

local function etc1RedBlocks()
	-- ETC1 individual mode: both subblocks use R=15, G=B=0 and table 0.
	-- Selector 0 adds +2, which clamps red to 255 and leaves G/B near zero.
	local red = string.char(0xff, 0x00, 0x00, 0x00, 0, 0, 0, 0)
	return {red, red, red}
end

local function makeKTXETC1()
	return makeKTX(0x8d64, etc1RedBlocks(), 0x1907)
end

local function makeKTXETC2RGB()
	-- ETC2 RGB accepts every valid ETC1 color block. Reusing the deterministic
	-- individual-mode red block therefore tests the ETC2 container/format path
	-- without depending on an external encoder.
	return makeKTX(0x9274, etc1RedBlocks(), 0x1907)
end

local function etc2RGBABlocks()
	-- EAC alpha base 255 with multiplier 0 decodes to opaque for every selector.
	local alpha = string.char(0xff, 0x00, 0, 0, 0, 0, 0, 0)
	local blocks = {}
	for index, color in ipairs(etc1RedBlocks()) do blocks[index] = alpha .. color end
	return blocks
end

local function etc2RGBA1RedBlocks()
	-- Deterministic opaque-red ETC2 RGB8A1 block generated by Xcode 18's
	-- TextureConverter 4.0 ETC2COMP backend at Highest quality.
	local red = string.char(0xfb, 0x00, 0xf0, 0x02, 0xff, 0xff, 0xff, 0xff)
	return {red, red, red}
end

local function makeKTXETC2RGBA()
	return makeKTX(0x9278, etc2RGBABlocks(), 0x1908)
end

local function makeKTXETC2RGBA1()
	return makeKTX(0x9276, etc2RGBA1RedBlocks(), 0x1907)
end

local function eacBlocks(channels, signed)
	-- Maximum positive EAC base codeword, multiplier 15, table 0, selector 7.
	-- This clamps every texel to +1 in both unsigned and signed formats. RG11
	-- stores two independent channel blocks in R, G order.
	local channel = string.char(signed and 0x7f or 0xff, 0xf0,
		0xff, 0xff, 0xff, 0xff, 0xff, 0xff)
	local block = channels == 2 and channel .. channel or channel
	return {block, block, block}
end

local function pvrtcRedBlocks(bitsPerPixel)
	-- Xcode 18 TextureConverter 4.0 PVRTC backend, Highest quality, opaque
	-- 8x8 red input. PVRTC keeps a 2x2-block minimum: 2bpp textures therefore
	-- has a 16x8 storage minimum while 4bpp has an 8x8 storage minimum, but both
	-- retain the source's 8x8 logical dimensions. Every mip payload is 32 bytes.
	local block = bitsPerPixel == 2
		and string.char(0x54, 0x55, 0x55, 0x55, 0x01, 0xfc, 0x00, 0xf8)
		or string.char(0x55, 0x55, 0x55, 0x55, 0x00, 0xfc, 0x00, 0xf8)
	local level = string.rep(block, 4)
	if bitsPerPixel == 2 then
		-- The 16x16 base level uses eight twiddled blocks. Lower levels use the
		-- same 32-byte minimum payload as the Xcode-generated reference.
		local base = string.char(
			0x54, 0x14, 0x10, 0x14, 0x01, 0xfc, 0x00, 0xf8,
			0x54, 0x55, 0x55, 0x55, 0x01, 0xfc, 0x00, 0xf8,
			0x01, 0x00, 0x10, 0x00, 0x01, 0xf8, 0x00, 0xf8,
			0x00, 0x00, 0x55, 0x00, 0x01, 0xfc, 0x00, 0xf8,
			0x54, 0x14, 0x10, 0x14, 0x01, 0xfc, 0x00, 0xf8,
			0x54, 0x55, 0x55, 0x55, 0x01, 0xfc, 0x00, 0xf8,
			0x01, 0x00, 0x10, 0x00, 0x01, 0xf8, 0x00, 0xf8,
			0x00, 0x00, 0x55, 0x00, 0x01, 0xfc, 0x00, 0xf8)
		return {base, level, level, level, level}
	end
	return {level, level, level, level}
end

local function makePVR(pixelFormat, blocks, width, height, channelType)
	width = width or 4
	height = height or 4
	return "PVR" .. string.char(3) .. u32(0) .. u64(pixelFormat)
		.. u32(0) .. u32(channelType or 0) .. u32(height) .. u32(width) .. u32(1)
		.. u32(1) .. u32(1) .. u32(#blocks) .. u32(0)
		.. table.concat(blocks)
end

local function assertPixel(image, x, y, expected, label)
	local red, green, blue, alpha = image:getPixel(x, y)
	assert(math.abs(red - expected[1]) < 0.04
		and math.abs(green - expected[2]) < 0.04
		and math.abs(blue - expected[3]) < 0.04 and alpha > 0.96,
		label .. ": " .. red .. "," .. green .. "," .. blue .. "," .. alpha)
end

