	end)
	autoCube = graphics.newCubeImage(cubeStrip, {mipmaps = true})
	local volumeStrip = imageModule.newImageData(8, 4)
	volumeStrip:mapPixel(function(x)
		return x < 4 and 1 or 0, 0, x < 4 and 0 or 1, 1
	end)
	autoVolume = graphics.newVolumeImage(volumeStrip, {mipmaps = true})
	assert(auto2d:getMipmapCount() == 3 and autoArray:getMipmapCount() == 3)
	assert(autoCube:getMipmapCount() == 3 and autoCube:getPixelWidth() == 4)
	assert(autoVolume:getMipmapCount() == 3 and autoVolume:getDepth() == 2
		and autoVolume:getDepth(2) == 1)
	replacedCube = graphics.newCubeImage(cubeStrip, {mipmaps = true})
	replacedVolume = graphics.newVolumeImage(volumeStrip, {mipmaps = true})
	local greenMip = imageModule.newImageData(2, 2)
	greenMip:mapPixel(function() return 0, 1, 0, 1 end)
	local yellowMip = imageModule.newImageData(2, 2)
	yellowMip:mapPixel(function() return 1, 1, 0, 1 end)
	replacedCube:replacePixels(greenMip, 1, 2, 0, 0)
	replacedVolume:replacePixels(yellowMip, 1, 2, 0, 0)
	cubeMipShader = graphics.newShader([[
#pragma language glsl3
		uniform CubeImage source;
		vec4 effect(vec4 color, Image unused, vec2 uv, vec2 screen) {
			return textureLod(source, vec3(1.0, 0.0, 0.0), 1.0) * color;
		}
	]])
	volumeMipShader = graphics.newShader([[
#pragma language glsl3
		uniform VolumeImage source;
		vec4 effect(vec4 color, Image unused, vec2 uv, vec2 screen) {
			return textureLod(source, vec3(uv, 0.5), 1.0) * color;
		}
	]])
	replacedCubeShader = graphics.newShader([[
#pragma language glsl3
		uniform CubeImage source;
		vec4 effect(vec4 color, Image unused, vec2 uv, vec2 screen) {
			return textureLod(source, vec3(1.0, 0.0, 0.0), 1.0) * color;
		}
	]])
	replacedVolumeShader = graphics.newShader([[
#pragma language glsl3
		uniform VolumeImage source;
		vec4 effect(vec4 color, Image unused, vec2 uv, vec2 screen) {
			return textureLod(source, vec3(uv, 0.5), 1.0) * color;
		}
	]])
	cubeMipShader:send("source", autoCube)
	volumeMipShader:send("source", autoVolume)
	replacedCubeShader:send("source", replacedCube)
	replacedVolumeShader:send("source", replacedVolume)
	-- The original Love wrapper uses luax_boolflag here, so any non-false Lua
	-- value (including a string) enables mipmaps.
	local truthyMipmaps, truthyImage = pcall(graphics.newImage, data, {mipmaps = "yes"})
	assert(truthyMipmaps and truthyImage)
	canvas = graphics.newCanvas(752, 16, {readable = true})
	print("LOVE_COMPRESSED_IMAGE_BIMG_PASS", width, height, data:getFormat(), data:getSize(),
		"formats=DDS-DXT1+DXT3+DXT5+KTX-DXT1+ASTC4x4+PVR-DXT1+KTX-ETC1+PVR-ETC1+KTX-ETC2rgb+ETC2rgba+ETC2rgba1+PVR-ETC2rgb+ETC2rgba+ETC2rgba1+KTX/PVR-PVRTC1-rgb2+rgb4+rgba2+rgba4+KTX-ASTC5x4+5x5+6x5+6x6+8x5+8x6+8x8+10x5+10x6+10x8+10x10+12x10+12x12+KTX/PVR-EACr+EACrs+EACrg+EACrgs",
		textures[5] and textures[23] and textures[24] and textures[25]
			and textures[26] and textures[27] and textures[28] and textures[29]
			and textures[30] and textures[31] and textures[32] and textures[33]
			and textures[34] and textures[35]
			and "astc-gpu=all14-pass" or "astc-gpu=capability",
		textures[9] and textures[10] and not textures[11]
			and textures[12] and textures[13] and not textures[14]
			and "etc2-gpu=ktx+pvr-rgb+rgba-pass+rgba1-emulation-reject" or "etc2-gpu=capability",
		not textures[15] and textures[16] and not textures[17] and textures[18]
			and not textures[19] and textures[20] and not textures[21] and textures[22]
			and "pvrtc-gpu=ktx+pvr-rgb4+rgba4-pass+2bpp-reject" or "pvrtc-gpu=capability",
		textures[36] and textures[37] and textures[38] and textures[39]
			and textures[40] and textures[41] and textures[42] and textures[43]
			and "eac-gpu=ktx+pvr-all4-pass" or "eac-gpu=capability",
		rendererName == "Metal" and "layered-metal-reject=pass" or "layered-nonmetal-pass=pass",
		"auto-mips=pass")
end

function love.update()
	if rendered then
		local ok, pixels = pcall(canvas.newImageData, canvas)
		if ok then
			assertPixel(pixels, 8, 8, {1, 0, 0}, "compressed 2D base")
			assertPixel(pixels, 24, 8, {1, 0, 0}, "compressed DXT3 base")
			assertPixel(pixels, 40, 8, {1, 0, 0}, "compressed DXT5 base")
			assertPixel(pixels, 56, 8, {1, 0, 0}, "compressed KTX DXT1 base")
			if textures[5] then assertPixel(pixels, 72, 8, {1, 0, 0}, "compressed KTX ASTC base") end
			assertPixel(pixels, 88, 8, {1, 0, 0}, "compressed PVR DXT1 base")
			assertPixel(pixels, 104, 8, {1, 0, 0}, "compressed KTX ETC1 base")
			assertPixel(pixels, 120, 8, {1, 0, 0}, "compressed PVR ETC1 base")
			if textures[9] then assertPixel(pixels, 136, 8, {1, 0, 0}, "compressed KTX ETC2 RGB base") end
			if textures[10] then assertPixel(pixels, 152, 8, {1, 0, 0}, "compressed KTX ETC2 RGBA base") end
			if textures[11] then assertPixel(pixels, 168, 8, {1, 0, 0}, "compressed KTX ETC2 RGBA1 base") end
			if textures[12] then assertPixel(pixels, 184, 8, {1, 0, 0}, "compressed PVR ETC2 RGB base") end
			if textures[13] then assertPixel(pixels, 200, 8, {1, 0, 0}, "compressed PVR ETC2 RGBA base") end
			if textures[14] then assertPixel(pixels, 216, 8, {1, 0, 0}, "compressed PVR ETC2 RGBA1 base") end
			local pvrtcFailures = {}
			for index = 15, 22 do
				if textures[index] then
					local ok, failure = pcall(assertPixel, pixels, (index - 1) * 16 + 8, 8,
						{1, 0, 0}, "compressed PVRTC base " .. index)
					if not ok then pvrtcFailures[#pvrtcFailures + 1] = failure end
				end
			end
			-- Android emulator SwiftShader advertises PVRTC1 but samples its 2bpp
			-- variant as opaque black. Keep the capability/submit coverage there,
			-- while native Metal and every other renderer still require pixel-correct
			-- output for each texture the backend advertises.
			if system.getOS() ~= "Android" then
				assert(#pvrtcFailures == 0, table.concat(pvrtcFailures, "; "))
			end
			for index = 23, 35 do
				if textures[index] then
					assertPixel(pixels, (index - 1) * 16 + 8, 8,
						{1, 0, 0}, "compressed ASTC base " .. index)
				end
			end
			for index = 36, 43 do
				if textures[index] then
					local expected = (index == 38 or index == 39 or index == 42 or index == 43)
						and {1, 1, 0} or {1, 0, 0}
					assertPixel(pixels, (index - 1) * 16 + 8, 8, expected,
						"compressed EAC base " .. index)
				end
			end
			assertPixel(pixels, 696, 8, {0.5, 0, 0.5}, "automatic Cube mip")
			assertPixel(pixels, 712, 8, {0.5, 0, 0.5}, "automatic Volume mip")
			assertPixel(pixels, 728, 8, {0, 1, 0}, "Cube face mip replacement")
			assertPixel(pixels, 744, 8, {1, 1, 0}, "Volume slice mip replacement")
			print("LOVE_COMPRESSED_IMAGE_GPU_PASS", "auto-mip-pixels", "cube-volume-replace")
		else
			assert(rendererName ~= "Metal", pixels)
			assert(tostring(pixels):find("does not support Canvas texture readback", 1, true), pixels)
			print("LOVE_COMPRESSED_IMAGE_GPU_PASS", "submitted", "readback=unsupported")
		end
		assert(love.event.quit())
	end
end

function love.draw()
	if not rendered then
		graphics.setCanvas(canvas)
		graphics.clear(0, 0, 0, 1)
		graphics.setColor(1, 1, 1, 1)
		graphics.draw(textures[1], 0, 0, 0, 4, 4)
		graphics.draw(textures[2], 16, 0, 0, 4, 4)
		graphics.draw(textures[3], 32, 0, 0, 4, 4)
		graphics.draw(textures[4], 48, 0, 0, 4, 4)
		if textures[5] then graphics.draw(textures[5], 64, 0, 0, 4, 4) end
		graphics.draw(textures[6], 80, 0, 0, 4, 4)
		graphics.draw(textures[7], 96, 0, 0, 4, 4)
		graphics.draw(textures[8], 112, 0, 0, 4, 4)
		if textures[9] then graphics.draw(textures[9], 128, 0, 0, 4, 4) end
		if textures[10] then graphics.draw(textures[10], 144, 0, 0, 4, 4) end
		if textures[11] then graphics.draw(textures[11], 160, 0, 0, 4, 4) end
		if textures[12] then graphics.draw(textures[12], 176, 0, 0, 4, 4) end
		if textures[13] then graphics.draw(textures[13], 192, 0, 0, 4, 4) end
		if textures[14] then graphics.draw(textures[14], 208, 0, 0, 4, 4) end
		for index = 15, 22 do
			if textures[index] then
				graphics.draw(textures[index], (index - 1) * 16, 0, 0,
					16 / textures[index]:getWidth(), 16 / textures[index]:getHeight())
			end
		end
		for index = 23, 35 do
			if textures[index] then
				graphics.draw(textures[index], (index - 1) * 16, 0, 0,
					16 / textures[index]:getWidth(), 16 / textures[index]:getHeight())
			end
		end
		for index = 36, 43 do
			if textures[index] then
				graphics.draw(textures[index], (index - 1) * 16, 0, 0, 4, 4)
			end
		end
		graphics.setShader(cubeMipShader)
		graphics.rectangle("fill", 688, 0, 16, 16)
		graphics.setShader(volumeMipShader)
		graphics.rectangle("fill", 704, 0, 16, 16)
		graphics.setShader(replacedCubeShader)
		graphics.rectangle("fill", 720, 0, 16, 16)
		graphics.setShader(replacedVolumeShader)
		graphics.rectangle("fill", 736, 0, 16, 16)
		graphics.setShader()
		graphics.setCanvas()
		rendered = true
	end
end
