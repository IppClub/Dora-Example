import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openModelLedger} from '../apps/server/model-ledger-sqlite.mjs';
test('queued intents persist without holds, cancel safely and recheck limits before admission',t=>{
 const dir=mkdtempSync(join(tmpdir(),'studio-queue-')),path=join(dir,'ledger.db');let ledger=openModelLedger(path);
 t.after(()=>{ledger.close();rmSync(dir,{recursive:true,force:true});});
 const configure=(kind,extra={})=>ledger.configure(kind,kind,{enabled:true,limit:1,amountLimit:100n,accountId:'account',apiId:'api',...extra},{actorId:'admin'});
 for(const kind of ['api','account','grant'])configure(kind);
 const make=requestId=>({requestId,accountId:'account',apiId:'api',grantId:'grant',fingerprint:requestId,reservation:10n,rates:{inputNanoCnyPerMillion:1n,outputNanoCnyPerMillion:1n}});
 ledger.reserve(make('active'));
 for(const key of ['next','cancel','revoked','poor'])assert.equal(ledger.reserve(make(key)).record.request.state,'queued');
 assert.equal(ledger.scope('account','account').reserved,10n);assert.equal(ledger.scope('api','api').active,1);
 ledger.close();ledger=openModelLedger(path);
 assert.equal(ledger.reserve(make('next')).replayed,true);
 assert.equal(ledger.admitQueued('next',1).decision.state,'queued');assert.equal(ledger.request('next').version,1);
 ledger.transition('cancel',1,'cancel');assert.equal(ledger.scope('account','account').reserved,10n);
 assert.throws(()=>ledger.admitQueued('cancel',2),/version conflict/);
 assert.throws(()=>ledger.beginByok({requestId:'next',accountId:'account',projectId:'project',configurationId:'key',model:'model',fingerprint:'next'}),/funding source/);
 configure('grant',{enabled:false});assert.equal(ledger.admitQueued('revoked',1).decision.reason,'unavailable');
 assert.equal(ledger.request('revoked').request.state,'rejected-before-dispatch');configure('grant');
 ledger.transition('active',1,'cancel');
 configure('account',{amountLimit:9n});assert.equal(ledger.admitQueued('poor',1).decision.reason,'insufficient-amount');configure('account');
 const admitted=ledger.admitQueued('next',1);assert.equal(admitted.record.request.state,'reserved');assert.equal(admitted.record.version,2);
 assert.equal(ledger.scope('api','api').active,1);assert.equal(ledger.scope('account','account').reserved,10n);
 assert.throws(()=>ledger.admitQueued('next',1),/version conflict/);
 assert.equal(ledger.transition('next',2,'dispatch').request.state,'in-flight');
});
