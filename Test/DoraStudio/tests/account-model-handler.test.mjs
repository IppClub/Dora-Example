import test from 'node:test';
import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {once} from 'node:events';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {randomBytes} from 'node:crypto';
import {openSessionStore} from '../apps/server/session-store.mjs';
import {openAccountStore} from '../apps/server/account-store.mjs';
import {openProjectStore} from '../apps/server/project-store.mjs';
import {openModelStores} from '../apps/server/model-stores.mjs';
import {createAccountModelHandler} from '../apps/server/account-model-handler.mjs';
import {SESSION_COOKIE_NAME} from '../apps/server/session-authenticate.mjs';

test('session and model settings share durable cookie authentication and live account revocation',async()=>{
 const dir=mkdtempSync(join(tmpdir(),'studio-account-model-')),path=join(dir,'store.db');
 const stores=openModelStores({path,providerIds:new Set(['fixture']),activeKeyId:'key',keys:new Map([['key',randomBytes(32)]])});
 const sessions=openSessionStore(path),accounts=openAccountStore(path),projects=openProjectStore(path);let handler;
 accounts.put('a',{enabled:true},{expectedVersion:0,actorId:'admin'});
 const server=createServer(async(req,res)=>{if(!await handler(req,res)){res.statusCode=404;res.end();}});
 try{
  server.listen(0,'127.0.0.1');await once(server,'listening');
  const origin=`http://127.0.0.1:${server.address().port}`;
  handler=createAccountModelHandler({studioOrigin:origin,sessions,accounts,projects,...stores,providers:[{id:'fixture',label:'Fixture'}]});
  projects.save('a',{requestId:'seed',baseRevision:0,name:'Private',snapshot:{version:1,projectId:'private',revision:1,entry:'init.lua',files:[{path:'init.lua',kind:'text',text:'print(1)'}]}});
  const {token}=sessions.issue('a',{ttlMs:60000});
  const get=(path,credential=token)=>fetch(origin+path,{headers:credential?{cookie:`${SESSION_COOKIE_NAME}=${credential}`,'x-account-id':'forged'}:{}});
  assert.deepEqual(await (await get('/api/session')).json(),{version:1,account:{accountId:'a'}});
  assert.equal((await get('/api/projects/private')).status,200);
  const upload={expectedAccountId:'a',requestId:'upload',baseRevision:0,name:'Uploaded',snapshot:{version:1,projectId:'uploaded',revision:8,entry:'init.lua',files:[{path:'init.lua',kind:'text',text:'print(8)'},{path:'binary.bin',kind:'binary',base64:'AP8='}]}};
  const put=(body,headers={origin})=>fetch(origin+'/api/projects/uploaded',{method:'PUT',headers:{cookie:`${SESSION_COOKIE_NAME}=${token}`,'content-type':'application/json',...headers},body:JSON.stringify(body)});
  assert.equal((await put(upload,{})).status,403);
  assert.equal((await put({...upload,expectedAccountId:'other'})).status,409);
  assert.equal(projects.get('a','uploaded'),null);
  assert.equal(projects.get('other','uploaded'),null);
  assert.equal((await put({...upload,owner:'forged'})).status,400);
  assert.equal((await put({...upload,snapshot:{...upload.snapshot,projectId:'wrong'}})).status,400);
  assert.equal((await put({...upload,snapshot:{...upload.snapshot,files:[upload.snapshot.files[0],{...upload.snapshot.files[1],base64:'not base64'}]}})).status,400);
  const written=await put(upload);assert.equal(written.status,200);assert.equal((await written.json()).cloudRevision,1);
  const replay=await put(upload);assert.equal(replay.status,200);assert.equal((await replay.json()).replayed,true);
  assert.equal(projects.usage('a').versions,2);
  assert.deepEqual(projects.get('a','uploaded').snapshot.files.find(file=>file.kind==='binary').bytes,new Uint8Array([0,255]));
  assert.equal((await put({...upload,requestId:'stale'})).status,409);
  assert.deepEqual(await (await get('/api/byok/providers')).json(),{version:1,providers:[{id:'fixture',label:'Fixture'}]});
  assert.equal((await get('/api/admin/accounts')).status,403);
  accounts.put('admin',{enabled:true,administrator:true},{expectedVersion:0,actorId:'bootstrap'});
  const adminToken=sessions.issue('admin',{ttlMs:60000}).token;
  assert.equal((await get('/api/admin/accounts',adminToken)).status,200);
  assert.equal((await get('/api/admin/accounts/a',adminToken)).status,200);
  assert.equal((await get('/api/admin/account-audit',adminToken)).status,200);
  assert.equal((await get('/api/projects/private',adminToken)).status,404);
  sessions.revoke(adminToken);
  assert.equal((await get('/api/admin/accounts',adminToken)).status,401);
  for(const path of ['/api/session','/api/byok/providers','/api/projects/private'])assert.equal((await get(path,'')).status,401);
  accounts.put('a',{enabled:false},{expectedVersion:1,actorId:'admin'});
  for(const path of ['/api/session','/api/byok/providers','/api/projects/private'])assert.equal((await get(path)).status,401);
  accounts.put('a',{enabled:true},{expectedVersion:2,actorId:'admin'});sessions.revoke(token);
  for(const path of ['/api/session','/api/byok/providers'])assert.equal((await get(path)).status,401);
  const replacement=sessions.issue('a',{ttlMs:60000});assert.equal((await get('/api/session',replacement.token)).status,200);
  const otherSession=sessions.issue('a',{ttlMs:60000});
  const logout=headers=>fetch(origin+'/api/session/logout',{method:'POST',headers:{cookie:`${SESSION_COOKIE_NAME}=${replacement.token}`,...headers}});
  assert.equal((await logout({})).status,403);
  assert.equal((await logout({origin:'https://foreign.test'})).status,403);
  assert.equal((await get('/api/session',replacement.token)).status,200);
  assert.equal((await get('/api/session/logout',replacement.token)).status,405);
  const loggedOut=await logout({origin});assert.equal(loggedOut.status,204);
  assert.equal(loggedOut.headers.get('set-cookie'),`${SESSION_COOKIE_NAME}=; Path=/; Max-Age=0; Secure; HttpOnly; SameSite=Lax`);
  assert.equal((await get('/api/session',replacement.token)).status,401);
  assert.equal((await get('/api/projects/private',replacement.token)).status,401);
  assert.equal((await get('/api/session',otherSession.token)).status,200);
  assert.equal((await logout({origin})).status,204);
  assert.equal((await get('/unrelated')).status,404);
 }finally{
  server.closeAllConnections();await new Promise(resolve=>server.close(resolve));projects.close();accounts.close();sessions.close();stores.close();rmSync(dir,{recursive:true,force:true});
 }
});
