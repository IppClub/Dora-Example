import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {randomBytes} from 'node:crypto';
import {createServer} from 'node:http';
import {once} from 'node:events';
import {openModelSecretVault} from '../apps/server/model-secret-vault.mjs';
import {createByokSecretRoute} from '../apps/server/model-byok-secret-route.mjs';
test('BYOK secret HTTP writes require ownership, explicit consent and matching version without echoing keys',async t=>{
 const dir=mkdtempSync(join(tmpdir(),'studio-byok-route-')),vault=openModelSecretVault(join(dir,'vault.db'),{activeKeyId:'test',keys:new Map([['test',randomBytes(32)]])});
 t.after(()=>{vault.close();rmSync(dir,{recursive:true,force:true});});
 let checks=0,revokeAfterFirst=false;
 const route=createByokSecretRoute({studioOrigin:'http://studio.test',vault,authorizeConfiguration:async(req,configurationId)=>{
  checks++;return req.headers.authorization==='fixture-owner'&&configurationId==='owned'&&!(revokeAfterFirst&&checks>1)?{accountId:'a',configurationId}:undefined;
 }});
 const server=createServer(async(req,res)=>{if(!await route(req,res)){res.statusCode=404;res.end();}});
 server.listen(0,'127.0.0.1');await once(server,'listening');
 t.after(()=>new Promise(resolve=>{server.closeAllConnections();server.close(resolve);}));
 const url=`http://127.0.0.1:${server.address().port}/api/byok/configurations/owned/secret`;
 const send=(method,body,headers={})=>fetch(url,{method,headers:{authorization:'fixture-owner',origin:'http://studio.test','content-type':'application/json',...headers},...(body?{body:JSON.stringify(body)}:{})});
 const valid={expectedVersion:0,key:'fixture-only-secret-测试-🔑',consent:true};
 const corrupt=Buffer.concat([Buffer.from('{"expectedVersion":0,"consent":true,"key":"'),Buffer.from([0xc3,0x28]),Buffer.from('"}')]);
 const malformed=await fetch(url,{method:'PUT',headers:{authorization:'fixture-owner',origin:'http://studio.test','content-type':'application/json'},body:corrupt});
 assert.equal(malformed.status,400);assert.equal(await malformed.text(),'');assert.equal(vault.metadata({kind:'byok',ownerId:'a',configurationId:'owned'}),undefined);
 assert.equal((await send('PUT',{...valid,key:'unpaired-\ud800'})).status,400);
 assert.equal(vault.metadata({kind:'byok',ownerId:'a',configurationId:'owned'}),undefined);
 assert.equal((await send('PUT',valid,{authorization:'foreign'})).status,404);
 assert.equal((await send('PUT',valid,{origin:'https://foreign.test'})).status,403);
 assert.equal((await send('PUT',{...valid,consent:false})).status,400);
 assert.equal((await send('PUT',{...valid,ownerId:'other'})).status,400);
 checks=0;revokeAfterFirst=true;assert.equal((await send('PUT',valid)).status,404);revokeAfterFirst=false;
 const saved=await send('PUT',valid);assert.equal(saved.status,200);assert.deepEqual(await saved.json(),{version:1,available:true});
 const metadata=await send('GET');assert.equal(metadata.headers.get('cache-control'),'private, no-store');assert.deepEqual(await metadata.json(),{version:1,available:true});
 await vault.withSecret({kind:'byok',ownerId:'a',configurationId:'owned'},bytes=>assert.equal(bytes.toString(),valid.key));
 assert.equal((await send('PUT',valid)).status,409);
 assert.equal((await send('PUT',{...valid,key:'x'.repeat(70000)})).status,413);
 assert.deepEqual(await (await send('DELETE',{expectedVersion:1})).json(),{version:2,available:false});
 await assert.rejects(vault.withSecret({kind:'byok',ownerId:'a',configurationId:'owned'},()=>{}),/unavailable/);
});
