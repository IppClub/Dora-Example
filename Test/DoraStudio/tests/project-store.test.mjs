import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openProjectStore} from '../apps/server/project-store.mjs';

test('cloud snapshots preserve bytes, isolate owners and atomically resolve retries and stale revisions',()=>{
  const dir=mkdtempSync(join(tmpdir(),'studio-project-store-')),path=join(dir,'db');let store=openProjectStore(path);const peer=openProjectStore(path);
  const snapshot={version:1,projectId:'game',revision:7,entry:'init.lua',files:[{path:'init.lua',kind:'text',text:'\ufeffprint("hello")\r\n'},{path:'image.bin',kind:'binary',bytes:new Uint8Array([0,255,128])}]};
  const save={requestId:'request-1',baseRevision:0,name:'初始名称',snapshot};
  try{
    assert.throws(()=>store.save('a',{requestId:'unnamed',baseRevision:0,snapshot}),/project name/);
    assert.deepEqual(store.save('a',save),{cloudRevision:1,replayed:false});
    assert.deepEqual(peer.save('a',save),{cloudRevision:1,replayed:true});
    assert.equal(peer.get('b','game'),null);
    const read=peer.get('a','game');assert.equal(read.name,'初始名称');assert.equal(read.snapshot.revision,7);
    assert.equal(read.snapshot.files.find(f=>f.kind==='text').text,snapshot.files[0].text);
    assert.deepEqual(read.snapshot.files.find(f=>f.kind==='binary').bytes,snapshot.files[1].bytes);
    assert.throws(()=>peer.save('a',{...save,requestId:'stale'}),/revision conflict/);
    assert.throws(()=>peer.save('a',{...save,baseRevision:1}),/request conflict/);
    const updated={...snapshot,revision:8,files:[{...snapshot.files[0],text:'print("updated")'},snapshot.files[1]]};
    assert.deepEqual(peer.save('a',{...save,name:'更新名称',requestId:'next',baseRevision:1,snapshot:updated}),{cloudRevision:2,replayed:false});
    assert.deepEqual(store.save('a',save),{cloudRevision:1,replayed:true});
    assert.equal(store.get('a','game').cloudRevision,2);
    const firstHistory=store.history('a','game',{limit:1});assert.equal(Number.isSafeInteger(firstHistory.items[0].updatedAt),true);assert.deepEqual(firstHistory.items.map(({updatedAt,...item})=>item),[{cloudRevision:1}]);assert.equal(firstHistory.nextCursor,1);
    const nextHistory=peer.history('a','game',{after:1,limit:1});assert.equal(Number.isSafeInteger(nextHistory.items[0].updatedAt),true);assert.deepEqual(nextHistory.items.map(({updatedAt,...item})=>item),[{cloudRevision:2}]);assert.equal(nextHistory.nextCursor,null);
    assert.deepEqual(peer.history('b','game'),{items:[],nextCursor:null});
    assert.equal(store.getVersion('b','game',1),null);
    const old=store.getVersion('a','game',1);assert.equal(old.name,'初始名称');old.snapshot.files[0].bytes[0]=77;
    assert.equal(store.getVersion('a','game',1).snapshot.files[0].bytes[0],0);
    assert.equal(store.getVersion('a','game',3),null);
    assert.equal(store.getVersion('a','game',1).snapshot.files.find(file=>file.kind==='text').text,snapshot.files[0].text);
    assert.equal(store.get('a','game').name,'更新名称');assert.equal(store.get('a','game').snapshot.files.find(file=>file.kind==='text').text,'print("updated")');
    store.save('a',{...save,requestId:'other',snapshot:{...snapshot,projectId:'second'}});
    const firstPage=store.list('a',{limit:1});assert.equal(Number.isSafeInteger(firstPage.items[0].updatedAt),true);assert.deepEqual(firstPage.items.map(({updatedAt,...item})=>item),[{projectId:'game',cloudRevision:2,name:'更新名称'}]);assert.equal(firstPage.nextCursor,'game');
    const secondPage=peer.list('a',{after:'game',limit:1});assert.equal(Number.isSafeInteger(secondPage.items[0].updatedAt),true);assert.deepEqual(secondPage.items.map(({updatedAt,...item})=>item),[{projectId:'second',cloudRevision:1,name:'初始名称'}]);assert.equal(secondPage.nextCursor,null);
    assert.deepEqual(peer.list('b'),{items:[],nextCursor:null});
    assert.throws(()=>store.list('a',{limit:101}),/limit/);
    assert.throws(()=>store.history('a','game',{after:-1}),/cursor/);
    assert.throws(()=>store.getVersion('a','game',0),/revision/);
    store.close();store=openProjectStore(path);assert.equal(store.get('a','game').cloudRevision,2);
    assert.deepEqual(store.save('a',save),{cloudRevision:1,replayed:true});
    assert.throws(()=>store.save('a',{...save,requestId:'unsafe',snapshot:{...snapshot,entry:'../bad'}}),/Invalid project save/);
    assert.equal(store.get('a','game').cloudRevision,2);
    assert.deepEqual(peer.remove('a','game'),{removed:true});
    assert.equal(store.get('a','game'),null);assert.deepEqual(store.history('a','game'),{items:[],nextCursor:null});
    assert.equal(store.list('a').items.some(item=>item.projectId==='game'),false);
    assert.deepEqual(store.remove('a','game'),{removed:false});
    assert.throws(()=>store.save('a',{...save,requestId:'after-delete'}),/Project was deleted/);
  }finally{peer.close();store.close();rmSync(dir,{recursive:true,force:true});}
});
