import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {once} from 'node:events';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openSessionStore} from '../apps/server/session-store.mjs';
import {openAccountStore} from '../apps/server/account-store.mjs';
import {openModelStores} from '../apps/server/model-stores.mjs';
import {createAdminSharedModelsHandler} from '../apps/server/admin-shared-models-handler.mjs';
import {SESSION_COOKIE_NAME} from '../apps/server/session-authenticate.mjs';

test('administrator can stage shared model, encrypted key and global capacity without exposing secrets or bypassing live auth',async()=>{
  const dir=mkdtempSync(join(tmpdir(),'studio-admin-shared-route-')),path=join(dir,'studio.sqlite');
  const stores=openModelStores({path,providerIds:new Set(['fixture']),activeKeyId:'fixture',keys:new Map([['fixture',new Uint8Array(32).fill(7)]])}),sessions=openSessionStore(path),accounts=openAccountStore(path);
  accounts.put('admin',{enabled:true,administrator:true},{expectedVersion:0,actorId:'bootstrap'});
  accounts.put('creator',{enabled:true,administrator:false},{expectedVersion:0,actorId:'bootstrap'});
  const admin=sessions.issue('admin',{ttlMs:60000}),creator=sessions.issue('creator',{ttlMs:60000});
  let handler,server;
  try{
    server=createServer(async(req,res)=>{if(!await handler(req,res)){res.statusCode=404;res.end();}});
    server.listen(0,'127.0.0.1');await once(server,'listening');
    const origin=`http://127.0.0.1:${server.address().port}`;
    handler=createAdminSharedModelsHandler({studioOrigin:origin,sessions,accounts,...stores});
    const request=(route,{method='GET',body,token=admin.token,requestOrigin=origin}={})=>fetch(origin+route,{method,headers:{...(token?{cookie:`${SESSION_COOKIE_NAME}=${token}`}:{}) ,...(method==='GET'?{}:{origin:requestOrigin,'content-type':'application/json'})},...(body===undefined?{}:{body:JSON.stringify(body)})});
    const base='/api/admin/shared-models/shared_api';
    const config={expectedVersion:0,label:'共享测试模型',model:'fixture-model',providerId:'fixture',enabled:false,pricing:{inputNanoCnyPerMillion:'1000000',outputNanoCnyPerMillion:'2000000'}};
    assert.equal((await request(base,{method:'PUT',body:config,token:null})).status,401);
    assert.equal((await request(base,{method:'PUT',body:config,token:creator.token})).status,403);
    assert.equal((await request(base,{method:'PUT',body:config,requestOrigin:'https://foreign.example'})).status,403);
    const created=await request(base,{method:'PUT',body:config});assert.equal(created.status,200);
    assert.equal((await created.json()).configuration.enabled,false);
    const staged=await request(base,{method:'PUT',body:{...config,expectedVersion:1,enabled:true}});
    assert.equal(staged.status,409,'enabled catalog record requires encrypted key and nonzero global scope');
    const secret=await request(base+'/secret',{method:'PUT',body:{expectedVersion:0,key:'test-only-provider-secret',consent:true}});
    assert.equal(secret.status,200);assert.deepEqual(await secret.json(),{version:1,available:true});
    const capacity=await request(base+'/limits',{method:'PUT',body:{enabled:true,limit:2}});
    assert.equal(capacity.status,200);assert.equal((await capacity.json()).api.limit,2);
    const enabled=await request(base,{method:'PUT',body:{...config,expectedVersion:1,enabled:true}});
    assert.equal(enabled.status,200);assert.equal((await enabled.json()).configuration.enabled,true);
    const detail=await request(base),serialized=await detail.text();assert.equal(detail.status,200);
    assert.equal(serialized.includes('test-only-provider-secret'),false);
    assert.deepEqual(JSON.parse(serialized).secret,{version:1,available:true});
    const list=await request('/api/admin/shared-models?limit=20'),listed=await list.text();assert.equal(list.status,200);
    assert.equal(listed.includes('test-only-provider-secret'),false);
    assert.equal(JSON.parse(listed).items[0].pricing.inputNanoCnyPerMillion,'1000000');
    assert.equal((await request('/api/admin/shared-models/missing')).status,404);
    assert.equal((await request(base+'/secret',{method:'DELETE',body:{expectedVersion:0}})).status,409);
    assert.equal((await request(base+'/secret',{method:'DELETE',body:{expectedVersion:1}})).status,409,'a live shared model cannot lose its secret');
    assert.equal((await request(base,{method:'PUT',body:{...config,expectedVersion:2,enabled:false}})).status,200);
    const revoked=await request(base+'/secret',{method:'DELETE',body:{expectedVersion:1}});
    assert.equal(revoked.status,200);assert.deepEqual(await revoked.json(),{version:2,available:false});
    assert.equal((await request(base,{method:'PUT',body:{...config,expectedVersion:3,enabled:true}})).status,409,'a revoked secret cannot be re-enabled');
    sessions.revoke(admin.token);
    assert.equal((await request(base+'/limits',{method:'PUT',body:{enabled:false,limit:0}})).status,401);
    assert.equal(stores.ledger.scope('api','shared_api').enabled,true);
  }finally{
    server?.closeAllConnections();if(server)await new Promise(resolve=>server.close(resolve));
    accounts.close();sessions.close();stores.close();rmSync(dir,{recursive:true,force:true});
  }
});
