import assert from 'node:assert/strict';
import createMatcher from '../packages/agent-contracts/dist/glob/matcher.mjs';
const module = await createMatcher();
const reset = module.cwrap('glob_reset', null, []);
const add = module.cwrap('glob_add', null, ['string']);
const compile = module.cwrap('glob_compile', null, []);
const match = module.cwrap('glob_match', 'number', ['string']);
const skip = module.cwrap('glob_skip_directory', 'number', ['string']);
const configure = patterns => { reset(); patterns.forEach(add); compile(); };
configure(['*.ts']);
assert.equal(match('main.ts'), 1);
assert.equal(match('dir/main.ts'), 0);
configure(['**/*.ts', '!**/.*/**', '!**/node_modules/**']);
assert.equal(match('main.ts'), 1);
assert.equal(match('dir/main.ts'), 1);
assert.equal(match('dir/main.lua'), 0);
assert.equal(skip('node_modules'), 1);
assert.equal(skip('dir/.cache'), 1);
assert.equal(skip('dir/visible'), 0);
configure(['**', '!**/*.ts', '**/keep.ts']);
assert.equal(match('a.ts'), 0);
assert.equal(match('keep.ts'), 1);
configure(['  dir\\?.[ty]s  ']);
assert.equal(match('dir/a.ts'), 1);
assert.equal(match('dir/ab.ts'), 0);
configure(['**']);
assert.equal(match('中文/游戏.ts'), 1);
console.log('PASS engine-extracted Wasm glob: root-only, recursive, ordered negation, directory pruning, normalization and UTF-8 paths');
