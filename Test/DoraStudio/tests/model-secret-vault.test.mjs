import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,readFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {randomBytes} from 'node:crypto';
import {DatabaseSync} from 'node:sqlite';
import {openModelSecretVault} from '../apps/server/model-secret-vault.mjs';
test('vault persists ciphertext, binds ownership and revokes with version checks',async t=>{
 const dir=mkdtempSync(join(tmpdir(),'studio-vault-')),path=join(dir,'vault.db'),master=randomBytes(32);
 let vault=openModelSecretVault(path,{activeKeyId:'v1',keys:new Map([['v1',master]])});
 const sql=new DatabaseSync(path);t.after(()=>{sql.close();vault.close();rmSync(dir,{recursive:true,force:true});});
 const binding={kind:'byok',ownerId:'a',configurationId:'config'},secret=Buffer.from('fixture-secret-never-a-real-api-key');
 assert.deepEqual(vault.put(binding,secret,{expectedVersion:0,actorId:'a'}),{version:1,available:true});
 let consumed;await vault.withSecret(binding,bytes=>{assert.deepEqual(bytes,secret);consumed=bytes;});assert.ok(consumed.every(value=>value===0));
 assert.throws(()=>vault.put(binding,secret,{expectedVersion:0,actorId:'a'}),/version conflict/);
 sql.exec("CREATE TRIGGER fail_secret_audit BEFORE INSERT ON model_secret_audit BEGIN SELECT RAISE(ABORT,'audit unavailable'); END;");
 assert.throws(()=>vault.put(binding,Buffer.from('replacement'),{expectedVersion:1,actorId:'a'}),/audit unavailable/);
 assert.equal(vault.metadata(binding).version,1);await vault.withSecret(binding,bytes=>assert.deepEqual(bytes,secret));
 sql.exec('DROP TRIGGER fail_secret_audit');
 await assert.rejects(vault.withSecret({...binding,ownerId:'b'},()=>{}),/unavailable/);
 const encrypted=sql.prepare('SELECT * FROM model_secrets').get();
 sql.prepare('INSERT INTO model_secrets VALUES(?,?,?,?,?,?,?,?)').run('byok','b','config',encrypted.version,encrypted.key_id,encrypted.nonce,encrypted.ciphertext,encrypted.tag);
 await assert.rejects(vault.withSecret({...binding,ownerId:'b'},()=>{}),/unavailable/);
 const damaged=Buffer.from(encrypted.ciphertext);damaged[0]^=1;
 sql.prepare("UPDATE model_secrets SET ciphertext=? WHERE owner_id='a'").run(damaged);
 await assert.rejects(vault.withSecret(binding,()=>{}),/unavailable/);
 vault.put(binding,secret,{expectedVersion:1,actorId:'a'});
 const rotated=randomBytes(32);
 vault.close();vault=openModelSecretVault(path,{activeKeyId:'v2',keys:new Map([['v1',master],['v2',rotated]])});
 await vault.withSecret(binding,bytes=>assert.deepEqual(bytes,secret));
 await vault.withSecret(binding,bytes=>vault.put(binding,bytes,{expectedVersion:2,actorId:'rotation-worker'}));
 vault.close();vault=openModelSecretVault(path,{activeKeyId:'v2',keys:new Map([['v2',rotated]])});
 await vault.withSecret(binding,bytes=>assert.deepEqual(bytes,secret));
 vault.revoke(binding,{expectedVersion:3,actorId:'a'});assert.equal(vault.metadata(binding).available,false);
 await assert.rejects(vault.withSecret(binding,()=>{}),/unavailable/);
 assert.equal(readFileSync(path).includes(secret),false);
 assert.equal(sql.prepare('SELECT COUNT(*) AS count FROM model_secret_audit').get().count,4);
});
