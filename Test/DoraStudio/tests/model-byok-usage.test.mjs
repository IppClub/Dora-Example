import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {DatabaseSync} from 'node:sqlite';
import {openModelLedger} from '../apps/server/model-ledger-sqlite.mjs';
test('BYOK journal records known usage once, preserves unknown and never charges platform funds',t=>{
 const dir=mkdtempSync(join(tmpdir(),'studio-byok-')),path=join(dir,'ledger.db');let ledger=openModelLedger(path);
 const fault=new DatabaseSync(path);t.after(()=>{fault.close();ledger.close();rmSync(dir,{recursive:true,force:true});});
 for(const accountId of ['a','b'])ledger.configure('account',accountId,{enabled:true,limit:2,amountLimit:100n},{actorId:'admin'});
 const request={requestId:'r',accountId:'a',projectId:'project',configurationId:'private-key-config',model:'chosen-model',fingerprint:'normalized-hash'};
 const before=ledger.scope('account','a');
 assert.equal(ledger.beginByok(request).replayed,false);assert.equal(ledger.beginByok(request).replayed,true);
 assert.throws(()=>ledger.beginByok({...request,accountId:'b'}),/binding mismatch/);
 assert.equal(ledger.byokUsagePage('a').length,1);assert.equal(ledger.byokUsagePage('a')[0].usage,null);
 assert.deepEqual(ledger.byokUsagePage('b'),[]);
 assert.throws(()=>ledger.recordByokUsage('b','r',1,{inputTokens:1n,outputTokens:1n}),/Unknown BYOK/);
 assert.throws(()=>ledger.recordByokUsage('a','r',1,null),/Invalid model usage/);
 fault.exec("CREATE TRIGGER fail_byok_audit BEFORE INSERT ON model_audit WHEN json_extract(NEW.data,'$.action')='byok-usage' BEGIN SELECT RAISE(ABORT,'audit failure'); END;");
 assert.throws(()=>ledger.recordByokUsage('a','r',1,{inputTokens:10n,outputTokens:2n}),/audit failure/);
 assert.equal(ledger.byokUsagePage('a')[0].state,'pending-usage');fault.exec('DROP TRIGGER fail_byok_audit');
 ledger.recordByokUsage('a','r',1,{inputTokens:10n,outputTokens:2n,cachedInputTokens:8n,reasoningOutputTokens:1n});
 assert.throws(()=>ledger.recordByokUsage('a','r',1,{inputTokens:10n,outputTokens:2n}),/version conflict/);
 ledger.beginByok({...request,requestId:'s'});ledger.close();ledger=openModelLedger(path);
 const rows=ledger.byokUsagePage('a');assert.equal(rows.length,2);assert.equal(rows[0].usage.inputTokens,10n);assert.equal(rows[0].usage.cachedInputTokens,8n);
 assert.equal(rows[1].usage,null);assert.equal(rows[1].state,'pending-usage');assert.equal(rows[0].fingerprint,undefined);assert.equal(rows[0].balance,undefined);
 assert.equal(ledger.byokUsagePage('a',{after:'r',limit:1})[0].requestId,'s');
 assert.deepEqual(ledger.scope('account','a'),before);
});
test('a durable request cannot switch between BYOK and platform funding',t=>{
 const dir=mkdtempSync(join(tmpdir(),'studio-funding-')),path=join(dir,'ledger.db');
 const first=openModelLedger(path),second=openModelLedger(path);
 t.after(()=>{second.close();first.close();rmSync(dir,{recursive:true,force:true});});
 for(const kind of ['api','account','grant'])first.configure(kind,kind,{enabled:true,limit:2,amountLimit:100n,accountId:'account',apiId:'api'},{actorId:'admin'});
 const platform={requestId:'platform',accountId:'account',apiId:'api',grantId:'grant',fingerprint:'same',reservation:10n,rates:{inputNanoCnyPerMillion:1n,outputNanoCnyPerMillion:1n}};
 const byok={requestId:'byok',accountId:'account',projectId:'project',configurationId:'key-config',model:'model',fingerprint:'same'};
 first.reserve(platform);
 const auditCount=first.audit().length;
 assert.throws(()=>second.beginByok({...byok,requestId:'platform'}),/funding source mismatch/);
 assert.equal(first.audit().length,auditCount);assert.deepEqual(second.byokUsagePage('account'),[]);
 second.beginByok(byok);
 assert.throws(()=>first.reserve({...platform,requestId:'byok'}),/funding source mismatch/);
 assert.equal(first.request('byok'),undefined);assert.equal(first.scope('account','account').reserved,10n);
 first.transition('platform',1,'cancel');
 assert.throws(()=>second.beginByok({...byok,requestId:'platform'}),/funding source mismatch/);
 assert.equal(first.scope('account','account').reserved,0n);
 assert.equal(second.beginByok(byok).replayed,true);
});
