import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createServer} from 'node:http';
import {once} from 'node:events';
import {openModelLedger} from '../apps/server/model-ledger-sqlite.mjs';
import {createModelAllowanceRoute} from '../apps/server/model-allowance-route.mjs';
test('allowance HTTP read uses authenticated ownership and exact live money without leaking shared details',async t=>{
 const dir=mkdtempSync(join(tmpdir(),'studio-allowance-')),ledger=openModelLedger(join(dir,'ledger.db'));
 t.after(()=>{ledger.close();rmSync(dir,{recursive:true,force:true});});
 const configure=(kind,key,extra={})=>ledger.configure(kind,key,{enabled:true,limit:1,amountLimit:100n,...extra},{actorId:'admin'});
 configure('api','api');configure('account','a');configure('account','b');
 configure('grant','g',{amountLimit:50n,accountId:'a',apiId:'api'});
 let origin;const route=createModelAllowanceRoute({studioOrigin:'http://studio.test',ledger,authenticate:async req=>req.headers.authorization==='fixture-a'?{accountId:'a'}:req.headers.authorization==='fixture-b'?{accountId:'b'}:null});
 const server=createServer(async(req,res)=>{if(!await route(req,res)){res.statusCode=404;res.end();}});
 server.listen(0,'127.0.0.1');await once(server,'listening');origin=`http://127.0.0.1:${server.address().port}`;
 t.after(()=>new Promise(resolve=>{server.closeAllConnections();server.close(resolve);}));
 const get=(token='fixture-a',path='g',headers={})=>fetch(`${origin}/api/model-grants/${path}/allowance`,{headers:{authorization:token,...headers}});
 assert.equal((await get('')).status,401);assert.equal((await get('fixture-b')).status,404);assert.equal((await get('fixture-b','missing')).status,404);
 assert.equal((await get('fixture-a','g',{origin:'https://foreign.test'})).status,403);
 const response=await get();assert.equal(response.headers.get('cache-control'),'private, no-store');
 const before=await response.json();assert.equal(before.available,'50');assert.equal(before.currency,'CNY');assert.equal(before.unit,'nano-CNY');assert.equal(before.apiId,undefined);
 ledger.reserve({requestId:'r',accountId:'a',apiId:'api',grantId:'g',fingerprint:'fixture',reservation:10n,rates:{inputNanoCnyPerMillion:1n,outputNanoCnyPerMillion:1n}});
 const held=await (await get()).json();assert.equal(held.available,'40');assert.equal(held.state,'concurrency');assert.equal(held.account.reserved,'10');assert.equal(held.grant.reserved,'10');
 configure('account','a',{amountLimit:25n});assert.equal((await (await get()).json()).available,'15');
 configure('api','api',{enabled:false});const disabled=await (await get()).json();assert.equal(disabled.available,null);assert.equal(disabled.state,'unavailable');
 configure('api','api');configure('account','a',{amountLimit:10n});const empty=await (await get()).json();assert.equal(empty.state,'insufficient-amount');assert.equal(empty.available,'0');
 assert.equal((await fetch(`${origin}/api/model-grants/g/allowance`,{method:'POST'})).status,405);
});
