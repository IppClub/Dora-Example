import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openSessionStore} from '../apps/server/session-store.mjs';
import {openAccountStore} from '../apps/server/account-store.mjs';
import {openModelStores} from '../apps/server/model-stores.mjs';

test('shared catalog pricing, vault and scope writes recheck live administrator session in their own SQLite transactions',t=>{
  const dir=mkdtempSync(join(tmpdir(),'studio-admin-model-')),path=join(dir,'studio.sqlite');
  const sessions=openSessionStore(path),accounts=openAccountStore(path),stores=openModelStores({path,providerIds:new Set(['fixture']),activeKeyId:'fixture',keys:new Map([['fixture',new Uint8Array(32).fill(7)]])});
  t.after(()=>{stores.close();accounts.close();sessions.close();rmSync(dir,{recursive:true,force:true});});
  accounts.put('admin',{enabled:true,administrator:true},{expectedVersion:0,actorId:'bootstrap'});
  accounts.put('creator',{enabled:true,administrator:false},{expectedVersion:0,actorId:'bootstrap'});
  const admin=sessions.issue('admin',{ttlMs:60000}),creator=sessions.issue('creator',{ttlMs:60000});
  const options={actorId:'admin',sessionToken:admin.token};
  const config={id:'shared_api',kind:'shared',ownerId:'platform',label:'共享配置',model:'fixture-model',providerId:'fixture',enabled:false,pricing:{inputNanoCnyPerMillion:'1000000',outputNanoCnyPerMillion:'2000000'}};
  const created=stores.catalog.put(config,{...options,expectedVersion:0});
  assert.deepEqual(created.pricing,config.pricing);
  assert.throws(()=>stores.catalog.put({...config,enabled:true},{...options,expectedVersion:1}),/Shared configuration not ready/);
  const binding={kind:'shared',ownerId:'platform',configurationId:'shared_api'};
  stores.vault.put(binding,new TextEncoder().encode('test-only-secret'),{...options,expectedVersion:0});
  stores.ledger.configure('api','shared_api',{enabled:true,limit:2},options);
  assert.deepEqual(stores.catalog.put({...config,enabled:true},{...options,expectedVersion:1}).pricing,config.pricing,'pricing survives an explicit config edit');
  assert.throws(()=>stores.catalog.put({...config,pricing:{inputNanoCnyPerMillion:'NaN',outputNanoCnyPerMillion:'2'}},{...options,expectedVersion:2}),/Invalid shared pricing/);
  stores.ledger.configure('account','creator',{enabled:true,limit:1,amountLimit:100n},options);
  stores.ledger.configure('grant','creator_shared_api',{enabled:true,limit:1,amountLimit:50n,accountId:'creator',apiId:'shared_api'},options);
  assert.equal(stores.ledger.scope('grant','creator_shared_api').amountLimit,50n);
  assert.throws(()=>stores.catalog.put({...config,enabled:false},{actorId:'creator',sessionToken:creator.token,expectedVersion:2}),/Administrator authorization required/);
  sessions.revoke(admin.token);
  assert.throws(()=>stores.catalog.put({...config,enabled:false},{...options,expectedVersion:2}),/Administrator session required/);
  assert.throws(()=>stores.vault.revoke(binding,{...options,expectedVersion:1}),/Administrator session required/);
  assert.throws(()=>stores.ledger.configure('api','shared_api',{enabled:false,limit:0},options),/Administrator session required/);
  assert.equal(stores.catalog.get('shared_api').enabled,true);
  assert.equal(stores.vault.metadata(binding).available,true);
  assert.equal(stores.ledger.scope('api','shared_api').enabled,true);
});
